/* Serialized by chrome.scripting into the selected GDH table page (MAIN world).
 * No saved URL/token, no automatic retry, no records leave this page.
 */
async function readGdhContractPage(){
 'use strict';
 const fail=code=>({ok:false,code});
 const origin='https://global-service.fa-cnc.idc-t.melco.co.jp';
 const path='/cncservice/tablemaintenance(2f)views(2f)table(5f)edit.jssprpc';
 const columns=['contract_id','contract_no','contract_type','contract_period','contract_start_date','contract_end_date','contract_from_location_code','contractor_id','contract_notes','nc_serial_no','del_flg','ins_user_id','upd_user_id','ins_date','ins_id','ins_pgmid','upd_date','upd_id','upd_pgmid'];
 if(location.origin!==origin||!location.pathname.startsWith('/cncservice/'))return fail('WRONG_PAGE');
 if(typeof window.createRequestData!=='function'||typeof window.server?.getData!=='function'||typeof window.ImJson?.toJSONString!=='function'||typeof window.ImAjax?.setContentTypeAndReqHeaders!=='function'||typeof window.ImJsspRpc?.receive!=='function')return fail('PAGE_NOT_READY');
 let request,url,body;
 try{
  const current=window.createRequestData();
  if(current?.db_source!=='ZALS'||current?.tablename!=='ZGDDTB_CONTRACT_INFO')return fail('WRONG_TABLE');
  // Read the URL generated by GDH for this page; never execute source text.
  const source=Function.prototype.toString.call(window.server.getData);
  const match=source.match(/ImJsspRpc\.sendJsspRpcRequest\(\s*(["'])([^"']+)\1\s*,\s*argsArray\s*,\s*null\s*,\s*null\s*,\s*["']post["']\s*\)/);
  if(!match)return fail('RPC_UNCONFIRMED');
  url=new URL(match[2],location.href);
  const keys=[...url.searchParams.keys()];
  if(url.origin!==origin||url.pathname!==path||url.username||url.password||url.hash||keys.length!==3||new Set(keys).size!==3||!keys.every(k=>['im_mark','im_func','im_from'].includes(k))||!url.searchParams.get('im_mark')||url.searchParams.get('im_func')!=='getData'||url.searchParams.get('im_from')!=='tablemaintenance(2f)views(2f)table(5f)edit')return fail('RPC_UNCONFIRMED');
  request={...current,pagenumber:'1',pageline:'100'};
  body=window.ImJson.toJSONString([request]);
  if(typeof body!=='string')return fail('INVALID_REQUEST');
 }catch{return fail('PAGE_NOT_READY');}
 return new Promise(resolve=>{
  let xhr=new XMLHttpRequest(),settled=false;
  const finish=value=>{if(settled)return;settled=true;clearTimeout(timer);resolve(value);};
  const timer=setTimeout(()=>{finish(fail('TIMEOUT'));try{xhr.abort();}catch{}},15000);
  try{
   xhr.open('POST',url.href,true);
   xhr=window.ImAjax.setContentTypeAndReqHeaders(xhr,'application/json; charset=utf-8');
   xhr.timeout=15000;
   xhr.onerror=()=>finish(fail('NETWORK_ERROR'));
   xhr.ontimeout=()=>finish(fail('TIMEOUT'));
   xhr.onabort=()=>finish(fail('ABORTED'));
   xhr.onload=()=>{
    try{
     if(xhr.status===401||xhr.status===403)return finish(fail('AUTH_REQUIRED'));
     if(xhr.status!==200)return finish(fail('HTTP_ERROR'));
     if(xhr.responseURL&&xhr.responseURL!==url.href)return finish(fail('AUTH_REQUIRED'));
     if(/html/i.test(xhr.getResponseHeader('Content-Type')||'')||/^\s*</.test(xhr.responseText))return finish(fail('AUTH_REQUIRED'));
     // Only JSON plus the observed bare undefined literal is accepted. Validate
     // without execution before delegating to GDH's legacy response decoder.
     const normalized=xhr.responseText.replace(/"(?:[^"\\]|\\.)*"|\bundefined\b/g,token=>token==='undefined'?'null':token);
     const envelope=JSON.parse(normalized);
     if(!envelope||typeof envelope!=='object'||Array.isArray(envelope))return finish(fail('INVALID_RESPONSE'));
     const response=window.ImJsspRpc.receive(xhr);
     if(!response||response.error!==false||!Array.isArray(response.data)||response.data.length>100||response.data.some(row=>!row||typeof row!=='object'||Array.isArray(row)))return finish(fail('INVALID_RESPONSE'));
     const data=response.data;
     const fields=[...new Set(data.flatMap(row=>Object.keys(row)))];
     const missingColumns=data.length?columns.filter(c=>data.some(row=>!Object.hasOwn(row,c))):[];
     const unexpectedColumns=fields.filter(c=>!columns.includes(c));
     // Page-local counts only. Preserve raw identifier equality and types;
     // no normalization, number coercion, joins or uniqueness claims beyond this page.
     const keyChecks=['contract_id','contract_no','nc_serial_no','contractor_id'].map(field=>{
      let blankCount=0,nonStringCount=0;const counts=new Map();
      for(const row of data){
       const value=Object.hasOwn(row,field)?row[field]:undefined;
       if(value==null||(typeof value==='string'&&!value.trim())){blankCount++;continue;}
       if(typeof value!=='string')nonStringCount++;
       // Ignore object-valued keys for equality; flag their type instead.
       if(typeof value!=='string'&&typeof value!=='number')continue;
       counts.set(value,(counts.get(value)||0)+1);
      }
      const duplicates=[...counts.values()].filter(count=>count>1);
      return {field,blankCount,nonStringCount,distinctCount:counts.size,duplicateValues:duplicates.length,duplicateRows:duplicates.reduce((sum,count)=>sum+count,0)};
     });
     finish({ok:true,source:'getData-live',keyChecks,summary:{count:data.length,fields,missingColumns,unexpectedColumns,valid:!missingColumns.length&&!unexpectedColumns.length},request:{db_source:'ZALS',tablename:'ZGDDTB_CONTRACT_INFO',pagenumber:1,pageline:100}});
    }catch{finish(fail('INVALID_RESPONSE'));}
   };
   xhr.send(body);
  }catch{finish(fail('NETWORK_ERROR'));}
 });
}
