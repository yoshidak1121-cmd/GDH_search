'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const destination=path.join(root,'dist','GDH_Search_Extension');
fs.mkdirSync(destination,{recursive:true});
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const worker=html.match(/<script id="worker-source" type="text\/plain">([\s\S]*?)<\/script>/);
const app=html.match(/<script>\s*('use strict';[\s\S]*?)<\/script>/);
const css=html.match(/<style>([\s\S]*?)<\/style>/);
if(!worker||!app||!css)throw Error('Viewer source layout changed; build must be reviewed');
const inlineWorker="const workerBlob=new Blob([$('worker-source').textContent],{type:'text/javascript'});\nconst workerURL=URL.createObjectURL(workerBlob);const worker=new Worker(workerURL);";
const appCode=app[1].replace(/\r\n/g,'\n');
if(!appCode.includes(inlineWorker))throw Error('Worker bootstrap changed; extension build must be reviewed');
fs.writeFileSync(path.join(destination,'worker.js'),worker[1]);
fs.writeFileSync(path.join(destination,'viewer.js'),appCode.replace(inlineWorker,"const worker=new Worker('worker.js');"));
fs.writeFileSync(path.join(destination,'viewer.css'),css[1]);
const viewer=html.replace(css[0],'<link rel="stylesheet" href="viewer.css">').replace(worker[0],'').replace(app[0],'<script src="bridge.js"></script>\n<script src="viewer.js"></script>');
if(/<script(?![^>]*src=)[^>]*>/i.test(viewer))throw Error('Inline script remains in extension viewer');
fs.writeFileSync(path.join(destination,'viewer.html'),viewer);
for(const name of ['manifest.json','content.js','bridge.js','popup.html','popup.js','popup.css'])fs.copyFileSync(path.join(root,'extension',name),path.join(destination,name));
fs.copyFileSync(path.join(root,'gdh-export.js'),path.join(destination,'gdh-export.js'));
if(fs.existsSync(path.join(root,'EXTENSION_INSTALL.md')))fs.copyFileSync(path.join(root,'EXTENSION_INSTALL.md'),path.join(destination,'INSTALL.md'));
console.log('Built: '+destination);
